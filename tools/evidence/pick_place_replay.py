"""Replay render of the recorded joint trajectory of the E2 pick_place demo, and its height plot.

Input: the MuJoCo joint positions that /mujoco_actuators_states reported during the live plugin
run (tools/sim_checks/record_motion.py --demo pick_place), 100 Hz. Nothing here simulates: every
frame sets the recorded joint positions on the same installed scene and runs MuJoCo's
kinematics (tools/sim_checks/kinematics.py).

The object is not grasped. The plugin offers no runtime weld or mocap control, so the live run
has no object at all. The render adds one, kinematically: a sphere resting on the table, placed
at the tool site from the lowest site point of the PICK dwell to that of the PLACE dwell, and
resting where it was released afterwards.

Outputs: the height plot (SVG, regenerated byte for byte and checked by
tools/evidence/tests/test_evidence.py) and, with --video, the MP4 and the GIF (encoder output,
not byte-checked; the data they draw are the data the tests check).

  python3 tools/evidence/pick_place_replay.py [--svg PATH] [--video] [--frames-dir DIR]
"""
import argparse
import gzip
import json
import os
import pathlib
import subprocess
import sys

# The render needs an offscreen GL context; the bindings read this when they are first imported.
os.environ.setdefault("MUJOCO_GL", "egl")

import matplotlib  # noqa: E402

matplotlib.use("svg")
import matplotlib.pyplot as plt  # noqa: E402

from common import MEDIA, ROOT, print_input, svg_metadata  # noqa: E402

sys.path.insert(0, str(ROOT / "tools" / "sim_checks"))
import pick_place  # noqa: E402
from expected import OBJECT_BELOW_SITE, OBJECT_HANG, OBJECT_RADIUS, TABLE_Z  # noqa: E402
from kinematics import MUJOCO_VERSION, Kinematics, scene_path  # noqa: E402

RECORDING = MEDIA / "e2-pick-place-recorded-joint-trajectory.json.gz"
SVG = MEDIA / "e2-pick-place-height.svg"
VIDEO_STEM = "e2-pick-place-replay-render-of-the-recorded-joint-trajectory"
MP4 = MEDIA / f"{VIDEO_STEM}.mp4"
GIF = MEDIA / f"{VIDEO_STEM}.gif"
RECORD_COMMAND = ("docker compose run --rm -T dev bash -c 'source install/release/setup.bash && "
                  "python3 tools/sim_checks/record_motion.py --demo pick_place "
                  "--out docs/media/e2-pick-place-recorded-joint-trajectory.json.gz'")
WIDTH, HEIGHT, FPS = 640, 480, 25
GIF_FPS, GIF_WIDTH = 10, 480
# A free camera in front of the arm, so the pick and place spots are both in view; the scene's
# `overview` camera (used by e2-baseline.mp4) sees the place spot behind the arm.
VIEW = {"lookat": (-0.05, 0.22, 0.2), "distance": 1.75, "azimuth": -70.0, "elevation": -24.0}
CAPTION = "replay render of the recorded joint trajectory - the object is drawn at the tool, not grasped"

INK, MUTED, GRID = "#0b0b0b", "#52514e", "#e4e3df"
BLUE, ORANGE, RED, AQUA = "#2a78d6", "#eb6834", "#e34948", "#1baf7a"


def load(path=RECORDING):
    with gzip.open(path, "rt", encoding="utf-8") as f:
        return json.load(f)


def samples(rec):
    """[(t s after the send, joint -> position)]."""
    return [(row[0], dict(zip(rec["joints"], row[1:]))) for row in rec["samples"]]


def judged(rec, kin):
    """pick_place.judge over the recording with its own schedule."""
    schedule = tuple(tuple(x) for x in rec["schedule"])
    return pick_place.judge(samples(rec), 0.0, lambda p: kin.site(p)[0][2], schedule)


def carried_interval(rec, kin):
    """(attach s, release s): the lowest site point of the first PICK dwell and of the first
    PLACE dwell."""
    reaches, _ = judged(rec, kin)
    first = {}
    for r in reaches:
        first.setdefault(r.name, r)
    return first["PICK"].lowest_s, first["PLACE"].lowest_s


def object_track(rec, kin):
    """[(t, object centre xyz, carried)] per sample. Carried: centre = site + OBJECT_BELOW_SITE
    along the tool axis. Before the attach and after the release the object rests on the table
    (centre at TABLE_Z + OBJECT_RADIUS) below where it is attached and released."""
    attach, release = carried_interval(rec, kin)
    track = []
    for t, p in samples(rec):
        pos, axis = kin.site(p)
        track.append((t, tuple(s + OBJECT_BELOW_SITE * a for s, a in zip(pos, axis)), attach <= t <= release))
    at_attach = next(c for t, c, _ in track if t == attach)
    at_release = next(c for t, c, _ in track if t == release)
    rest_pick = (at_attach[0], at_attach[1], TABLE_Z + OBJECT_RADIUS)
    rest_place = (at_release[0], at_release[1], TABLE_Z + OBJECT_RADIUS)
    return [(t, c if carried else (rest_pick if t < attach else rest_place), carried) for t, c, carried in track]


def plot_data(rec, kin):
    """What the height plot draws: t, the attachment_site height and the object's lowest point
    per sample (m), the dwells [(name, arrive, leave)], the carried interval and the reference
    heights, all from the recording through MuJoCo's kinematics."""
    t, site_z, low = [], [], []
    for (ts, p), (_, centre, _) in zip(samples(rec), object_track(rec, kin)):
        t.append(ts)
        site_z.append(kin.site(p)[0][2])
        low.append(centre[2] - OBJECT_RADIUS)
    _, heights = judged(rec, kin)
    return {"t": t, "site_z": site_z, "object_low": low,
            "dwells": [tuple(x) for x in rec["schedule"]], "carried": carried_interval(rec, kin),
            "carry_min_z": pick_place.CARRY_MIN_Z, "table_z": TABLE_Z,
            "lowest_pick_to_release": heights["pick_to_place"], "lowest_lift_to_place_approach": heights["carry"]}


def draw_svg(rec, out, kin):
    plt.rcParams.update({"svg.hashsalt": "e2-pick-place-height", "font.size": 10,
                         "font.family": "DejaVu Sans"})
    d = plot_data(rec, kin)
    fig, ax = plt.subplots(figsize=(9, 4.4), facecolor="white")
    ax.set_facecolor("white")
    a, b = d["carried"]
    ax.axvspan(a, b, color=AQUA, alpha=0.10, linewidth=0)
    ax.text((a + b) / 2, 0.40, "object drawn at the tool (carried)", color=MUTED, ha="center",
            fontsize=8.5)
    for name, arrive, leave in d["dwells"]:
        ax.axvspan(arrive, leave, color=MUTED, alpha=0.12, linewidth=0)
        ax.text((arrive + leave) / 2, -0.035, name.replace("_", "\n"), color=INK, ha="center", va="top",
                fontsize=7)
    ax.plot(d["t"], d["site_z"], color=BLUE, linewidth=1.6, label="attachment_site height (MuJoCo kinematics)")
    ax.plot(d["t"], d["object_low"], color=ORANGE, linewidth=1.2,
            label=f"drawn object's lowest point (sphere r {OBJECT_RADIUS:.3f} m, {OBJECT_HANG:.3f} m below the site)")
    ax.axhline(d["table_z"], color=INK, linewidth=1.0)
    ax.text(d["t"][-1], d["table_z"] + 0.006, "table (floor plane, z 0) ", color=INK, ha="right", fontsize=8)
    ax.axhline(d["carry_min_z"], color=RED, linewidth=1.0, linestyle="--")
    ax.text(0.15, d["carry_min_z"] - 0.008, f"LIFT to PLACE_APPROACH floor {d['carry_min_z']} m (sim check)",
            color=RED, ha="left", va="top", fontsize=8)
    ax.set_xlim(0, d["t"][-1])
    ax.set_ylim(-0.11, 0.64)
    ax.set_xlabel("simulation time since the goal was sent (s); grey: waypoint dwells", color=INK)
    ax.set_ylabel("height (m)", color=INK)
    ax.set_title("E2 pick_place demo: recorded MuJoCo joint positions through MuJoCo's kinematics\n"
                 f"lowest site point PICK to release {d['lowest_pick_to_release']:.4f} m, LIFT to PLACE_APPROACH "
                 f"{d['lowest_lift_to_place_approach']:.4f} m; no grasp physics", color=INK, fontsize=10.5)
    ax.legend(loc="upper left", fontsize=8, frameon=False)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(MUTED)
    ax.tick_params(colors=MUTED)
    fig.tight_layout()
    fig.savefig(out, format="svg", facecolor="white", metadata=svg_metadata())
    plt.close(fig)


def phase(t, schedule):
    """The waypoint whose dwell holds t, else the move toward the next one."""
    for name, arrive, leave in schedule:
        if t < arrive:
            return f"moving to {name}"
        if t <= leave:
            return f"at {name}"
    return "holding HOME"


def frames(rec, kin):
    """Yields (t, carried, RGB uint8 HEIGHT x WIDTH x 3) at FPS, from the sample at or before
    each frame time."""
    import mujoco
    import numpy as np

    spec = mujoco.MjSpec.from_file(str(scene_path()))
    body = spec.worldbody.add_body(name="drawn_object", mocap=True)
    body.add_geom(type=mujoco.mjtGeom.mjGEOM_SPHERE, size=[OBJECT_RADIUS, 0, 0], rgba=[0.85, 0.15, 0.12, 1],
                  contype=0, conaffinity=0)
    model = spec.compile()
    data = mujoco.MjData(model)
    mocap = model.body("drawn_object").mocapid[0]
    renderer = mujoco.Renderer(model, HEIGHT, WIDTH)
    camera = mujoco.MjvCamera()
    camera.type = mujoco.mjtCamera.mjCAMERA_FREE
    camera.lookat[:] = VIEW["lookat"]
    camera.distance, camera.azimuth, camera.elevation = VIEW["distance"], VIEW["azimuth"], VIEW["elevation"]
    try:
        rows, track = samples(rec), object_track(rec, kin)
        i = 0
        for k in range(int(rows[-1][0] * FPS) + 1):
            t = k / FPS
            while i + 1 < len(rows) and rows[i + 1][0] <= t + 1e-9:
                i += 1
            for joint, value in rows[i][1].items():
                data.qpos[model.joint(joint).qposadr[0]] = value
            data.mocap_pos[mocap] = track[i][1]
            mujoco.mj_kinematics(model, data)
            mujoco.mj_camlight(model, data)  # camera and light poses; mj_kinematics leaves them unset
            renderer.update_scene(data, camera=camera)
            yield t, track[i][2], np.ascontiguousarray(renderer.render())
    finally:
        renderer.close()


def annotate(image, t, carried, schedule):
    from matplotlib import font_manager
    from PIL import Image, ImageDraw, ImageFont

    img = Image.fromarray(image)
    draw = ImageDraw.Draw(img)
    font = ImageFont.truetype(font_manager.findfont("DejaVu Sans"), 14)
    small = ImageFont.truetype(font_manager.findfont("DejaVu Sans"), 12)
    draw.rectangle((0, 0, WIDTH, 22), fill=(0, 0, 0))
    draw.text((8, 4), CAPTION, fill=(255, 255, 255), font=small)
    draw.rectangle((0, HEIGHT - 26, WIDTH, HEIGHT), fill=(0, 0, 0))
    state = "object carried (drawn at the tool)" if carried else "object resting on the table"
    draw.text((8, HEIGHT - 22), f"t {t:5.2f} s   {phase(t, schedule)}   {state}", fill=(255, 255, 255), font=font)
    return img


def render_video(rec, kin, mp4, gif, frames_dir=None):
    """Encodes the frames to an H.264 MP4, then a palette GIF from the MP4. Both are written to
    partial files and renamed on success."""
    schedule = tuple(tuple(x) for x in rec["schedule"])
    part_mp4 = mp4.with_name(f".{mp4.name}.partial.mp4")
    part_gif = gif.with_name(f".{gif.name}.partial.gif")
    ffmpeg = subprocess.Popen(
        ["ffmpeg", "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{WIDTH}x{HEIGHT}",
         "-r", str(FPS), "-i", "-", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "28",
         "-map_metadata", "-1", "-fflags", "+bitexact", "-movflags", "+faststart", str(part_mp4)],
        stdin=subprocess.PIPE)
    try:
        for k, (t, carried, image) in enumerate(frames(rec, kin)):
            img = annotate(image, t, carried, schedule)
            if frames_dir is not None and k % FPS == 0:
                img.save(pathlib.Path(frames_dir) / f"frame-{t:05.2f}.png")
            ffmpeg.stdin.write(img.tobytes())
    finally:
        ffmpeg.stdin.close()
        code = ffmpeg.wait()
    if code != 0:
        part_mp4.unlink(missing_ok=True)
        raise SystemExit(f"ffmpeg (mp4) exited {code}")
    vf = (f"fps={GIF_FPS},scale={GIF_WIDTH}:-1:flags=lanczos,split[a][b];"
          "[a]palettegen=max_colors=64:stats_mode=diff[p];[b][p]paletteuse=dither=bayer:bayer_scale=4")
    gif_run = subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(part_mp4), "-vf", vf,
                              "-map_metadata", "-1", "-f", "gif", str(part_gif)])
    if gif_run.returncode != 0:
        part_mp4.unlink(missing_ok=True)
        part_gif.unlink(missing_ok=True)
        raise SystemExit(f"ffmpeg (gif) exited {gif_run.returncode}")
    os.replace(part_mp4, mp4)
    os.replace(part_gif, gif)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--in", dest="src", default=str(RECORDING))
    parser.add_argument("--svg", default=str(SVG))
    parser.add_argument("--video", action="store_true", help=f"also write {MP4.name} and {GIF.name}")
    parser.add_argument("--frames-dir", help="with --video: also save one annotated PNG per second here")
    args = parser.parse_args(argv)
    print_input(os.path.relpath(args.src, ROOT), RECORD_COMMAND)
    rec = load(args.src)
    kin = Kinematics()
    reaches, heights = judged(rec, kin)
    problems = pick_place.failures(reaches, heights)
    if problems:
        raise SystemExit(f"{args.src} fails the simulation check's conditions: {problems}")
    for r in reaches:
        print(f"{r.name:15s} best largest-joint error {r.best_error:.4f} rad, lowest site z {r.lowest_z:.4f} m")
    print(f"lowest site z from PICK reached to the release in the PLACE dwell {heights['pick_to_place']:.4f} m "
          f"(object's lowest point {heights['pick_to_place'] - OBJECT_HANG:+.4f} m), from LIFT to PLACE_APPROACH "
          f"{heights['carry']:.4f} m; carried from {carried_interval(rec, kin)[0]:.3f} s to "
          f"{carried_interval(rec, kin)[1]:.3f} s")
    draw_svg(rec, args.svg, kin)
    print(f"wrote {args.svg}")
    if args.video:
        render_video(rec, kin, MP4, GIF, args.frames_dir)
        print(f"wrote {MP4} and {GIF} (MuJoCo {MUJOCO_VERSION})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
