"""An annotated frame trace of one SYNC cycle of our CANopen master, from the X1 recording.

Lists every frame on vcan_host (what canopen_master_cli sent and received) from SYNC j, the SYNC
our master sends right before it dispatches command seq k to the six drives, up to the last TPDO
after SYNC j+1, the SYNC at which the drives actuate seq k. The master's `dispatch` record and
the bank's actuation records are placed by their own stamps. The window is before X1's fault
onset (the healthy stream). PDOs are decoded through the EDS mapping of tools/od/wire.py.
Writes docs/media/e3c-master-frame-trace.txt.

  python3 tools/evidence/master_frame_trace.py [--row x1] [--seq 10] [--out PATH]
"""
import argparse
import sys

from common import (MEDIA, NODE, decode, frames, load_recording, print_input,
                    recording_command)
from frame_trace import SYNC_COB, deadline_ms, label_of, statusword_state

LEASE_MS = 48  # The host rule: a command's valid_until never exceeds now + lease (spec 6.2).


def node_tags(obs, k):
    """{node: exec_tag} of the RPDO1 of seq k that each node received from the master."""
    tags = {}
    for t, c, d in frames(obs, "host"):
        found = label_of(c)
        if found and found[0] == "RPDO1" and len(d) == 8:
            v = decode("RPDO1", d)
            if v["command_seq"] == k:
                tags.setdefault(found[1], v["exec_tag"])
    return tags


def note(t, label, node, v, k, after_j1):
    if label == "RPDO1":
        if v["command_seq"] != k:
            return f"seq {v['command_seq']}, the next command: its own cycle starts here"
        return (f"command seq {k}, first fragment: target and seq bound to node {node}'s tag"
                if node == NODE else f"as node {NODE}, under node {node}'s own tag")
    if label == "RPDO2":
        if v["command_seq"] != k:
            return f"seq {v['command_seq']}, the next command"
        if node != NODE:
            return f"as node {NODE}"
        left = deadline_ms(v["valid_until_us"], t)
        return (f"command seq {k}, second fragment: deadline {left:.1f} ms after this frame "
                f"(the host never sends one beyond now + {LEASE_MS} ms); the pair waits for the "
                f"next SYNC (D7)")
    if node != NODE:
        return f"node {node}, sampled at the SYNC before it"
    if label == "TPDO1":
        return (f"sampled at the SYNC before it: statusword 0x{v['statusword']:04X} = "
                f"{statusword_state(v['statusword'])}")
    if label == "TPDO2":
        side = "after" if after_j1 else "before"
        return (f"applied_seq {v['applied_seq']}: the command the drive accepted at the SYNC "
                f"before it ({side} seq {k}'s actuation); drive verification, not plant motion")
    return "applied_tag: the tag of applied_seq; the master joins TPDO1-3 by sample_seq"


def build(obs, k, row):
    dispatch = [e for e in obs["cli"] if e.get("event") == "dispatch" and e["seq"] == k]
    if len(dispatch) != 1:
        raise SystemExit(f"seq {k}: {len(dispatch)} dispatch records")
    if not dispatch[0]["approved"]:
        raise SystemExit(f"seq {k} is an arm hold, not an approved command")
    tags = node_tags(obs, k)
    if sorted(tags) != list(range(1, 7)):
        raise SystemExit(f"seq {k} reached nodes {sorted(tags)} on vcan_host, not 1-6")
    first = min(t for t, c, d in frames(obs, "host")
                if label_of(c) and label_of(c)[0] == "RPDO1" and len(d) == 8 and
                decode("RPDO1", d)["command_seq"] == k)
    syncs = [t for t, _, _ in frames(obs, "host", {SYNC_COB})]
    j = max(i for i, s in enumerate(syncs) if s < first)
    t_j, t_j1 = syncs[j], syncs[j + 1]
    tpdo_after = [t for t, c, _ in frames(obs, "host", None, t_j1, syncs[j + 2])
                  if label_of(c) and label_of(c)[0].startswith("TPDO")]
    t_end = tpdo_after[-1]
    act = [r for r in obs["bank"] if r.get("event") == "drive" and r.get("kind") == "actuated"
           and r["seq"] == k]
    if sorted(r["node"] for r in act) != list(range(1, 7)):
        raise SystemExit(f"seq {k}: actuation records of nodes {sorted(r['node'] for r in act)}")
    t_act = min(r["t_ns"] for r in act) / 1e9
    t_dispatch = dispatch[0]["at_ns"] / 1e9

    lines = [
        f"E3c master frame trace: one SYNC cycle of canopen_master_cli on vcan_host (what our "
        f"master sent and received), command seq {k} to nodes 1-6",
        f"source: tools/interop/recorded/{row}.json.gz, the recorded observation of "
        f"test_short_feedback_outage_latches_inhibit (fault row X1), before its fault onset",
        "generated by: python3 tools/evidence/master_frame_trace.py "
        "(PDOs decoded with the EDS mapping of tools/od/wire.py, config/od/vdrive_arm.eds)",
        "times: ms since SYNC j, CLOCK_MONOTONIC as the capture socket's reader stamped each "
        "frame; the master and the bank stamp their own records",
        "units: target_position and position_actual_value in urad, velocity_actual_value in "
        "urad/s, valid_until_us and sample_time_us in host us mod 2^32",
        f"tags: each node issued its own tag at arming: "
        + ", ".join(f"node {n} {tags[n]}" for n in sorted(tags)),
        "",
        f"{'t_ms':>8}  {'COB':>3}  {'data':<16}  decoded / note",
    ]
    marks = [(t_dispatch, f"master record: dispatch seq {k} (approved, from write "
                          f"{dispatch[0]['source_seq']}) to the six nodes"),
             (t_act, f"bank trace: actuated seq {k} on nodes 1-6, each under its own tag")]
    seen_sync = 0
    for t, c, d in frames(obs, "host", None, t_j - 1e-9, t_end + 1e-9):
        while marks and marks[0][0] <= t:
            mt, text = marks.pop(0)
            lines.append(f"{(mt - t_j) * 1e3:8.3f}  {'':>3}  {'':<16}  {text}")
        if c == SYNC_COB:
            seen_sync += 1
            if seen_sync == 1:
                lines.append(f"{(t - t_j) * 1e3:8.3f}  {c:03X}  {'':<16}  SYNC j, sent by our "
                             f"master: opens the window in which seq {k} goes out")
            else:
                lines.append(f"{(t - t_j) * 1e3:8.3f}  {c:03X}  {'':<16}  SYNC j+1, sent by our "
                             f"master: the drives actuate seq {k} here (D7); the TPDOs that "
                             f"follow are sampled here")
            continue
        found = label_of(c)
        if found is None:
            lines.append(f"{(t - t_j) * 1e3:8.3f}  {c:03X}  {d.hex():<16}  not a PDO")
            continue
        label, node = found
        v = decode(label, d)
        fields = " ".join(f"{name}=0x{value:04X}" if name == "statusword" else f"{name}={value}"
                          for name, value in v.items())
        lines.append(f"{(t - t_j) * 1e3:8.3f}  {c:03X}  {d.hex():<16}  node {node} {label} "
                     f"{fields}")
        lines.append(f"{'':8}  {'':>3}  {'':<16}    -> "
                     f"{note(t, label, node, v, k, seen_sync == 2)}")
    for mt, text in marks:
        lines.append(f"{(mt - t_j) * 1e3:8.3f}  {'':>3}  {'':<16}  {text}")
    lines.append("")
    lines.append(f"SYNC j to SYNC j+1: {(t_j1 - t_j) * 1e3:.3f} ms on the capture clock")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--row", default="x1")
    parser.add_argument("--seq", type=int, default=10)
    parser.add_argument("--out", default=str(MEDIA / "e3c-master-frame-trace.txt"))
    args = parser.parse_args(argv)
    print_input(f"tools/interop/recorded/{args.row}.json.gz", recording_command(args.row))
    text = build(load_recording(args.row), args.seq, args.row)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
